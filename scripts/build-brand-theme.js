// Extract color-only overrides from the authored export; preserve media contexts.
// No layout, image URL, typography or animation declarations are copied/changed.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const colors = {
  '#000000': 'var(--mb-navy)', '#000000D6': '#002040D6',
  '#101010': 'var(--mb-navy)', '#707070': 'var(--mb-blue)',
  '#F2B72F': 'var(--mb-cyan)', '#F2B72FD9': '#36C2FFD9', '#ffab00': 'var(--mb-cyan)',
  '#F9F6EF': 'var(--mb-paper)', '#EDE8E2': 'var(--mb-silver)'
};
function extract(css) {
  let result = '', start = 0;
  while (start < css.length) {
    const open = css.indexOf('{', start);
    if (open < 0) break;
    let depth = 1, end = open + 1;
    while (depth && end < css.length) { if (css[end] === '{') depth++; if (css[end] === '}') depth--; end++; }
    const selector = css.slice(start, open).trim();
    const body = css.slice(open + 1, end - 1);
    if (selector.startsWith('@media')) {
      const nested = extract(body);
      if (nested) result += `${selector}{\n${nested}}\n`;
    } else if (!selector.startsWith('@')) {
      const declarations = body.split(';').filter(d => !d.trim().startsWith('--')).map(d => {
        const colon = d.indexOf(':');
        if (colon < 0) return '';
        const prop = d.slice(0, colon).trim(), value = d.slice(colon + 1);
        if (!/^(color|fill|stroke|background-color|background-image|border-color|box-shadow)$/.test(prop)) return '';
        let mapped = value.replace(/#[\da-f]{6,8}\b/gi, hex => colors[hex.toUpperCase()] || colors[hex] || hex);
        if (/^(color|fill|stroke)$/.test(prop)) mapped = mapped.replace(/var\(--mb-cyan\)/g, 'var(--mb-blue)').replace(/var\(\s*--e-global-color-accent\s*\)/g, 'var(--mb-blue)');
        return mapped !== value ? `${prop}:${mapped};` : '';
      }).join('');
      if (declarations) result += `${selector}{${declarations}}\n`;
    }
    start = end;
  }
  return result;
}
const dir = path.join(root, 'assets/wp-content/uploads/elementor/css');
const output = '/* Generated by scripts/build-brand-theme.js. Edit mb-brand-v1.css for theme tokens. */\n' +
  fs.readdirSync(dir).sort().map(file => extract(fs.readFileSync(path.join(dir, file), 'utf8'))).join('');
fs.writeFileSync(path.join(root, 'assets/mb-brand-export-v1.css'), output);
console.log('Brand color overrides generated');
